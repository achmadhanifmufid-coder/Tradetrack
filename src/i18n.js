// Unknown keys fall back to the key itself, so raw error messages pass through untouched.
export const translate = (lang, key, vars = {}) =>
  (dict[lang][key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');

export const LangContext = createContext('id');
export function useT() {
  const lang = useContext(LangContext);
  return (key, vars) => translate(lang, key, vars);
}

export function savedLang() {
  try {
    return localStorage.getItem('lang') === 'en' ? 'en' : 'id';
  } catch {
    return 'id';
  }
}
export function saveLang(lang) {
  try {
    localStorage.setItem('lang', lang);
  } catch {
    // private mode / blocked storage: language just won't be remembered
  }
}
